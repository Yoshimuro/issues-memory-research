#!/bin/bash
# «Почему не сразу TurboFan»: цена компиляции по ярусам и старт настоящего приложения под принудительным ярусом.
#   ./docker/run.sh 24 'bash docker/why-not-turbofan.sh'   (шаг 11 docker/verify.sh)
# --always-turbofan есть только до V8 13.9: в V8 14+ флага нет (bad option). На Node 24 он только ПРОСИТ TurboFan:
# функцию берут в оптимизацию не раньше второго вызова (--minimum-invocations-before-optimization=2).
echo "## компиляция наших функций (--trace-opt: подготовка, компиляция, установка, мс — три фазы, складывать)"
node --allow-natives-syntax --trace-opt lab/shape-analyzer.js lab/ref-a.js 2>&1 | grep -E "completed compiling.*<JSFunction (score|normalizeUser)" | sed -E "s/0x[0-9a-f]+ //g; s/ \(sfi = [^)]*\)//"
NPM=$(dirname "$(readlink -f "$(which npm)")")/npm-cli.js
t() { local s=$(date +%s%N); "$@" >/dev/null 2>&1; echo $(( ($(date +%s%N)-s)/1000000 )); }
echo "## старт npm --version, мс (5 прогонов; первый — холодный кэш файлов)"
for m in "" "--always-sparkplug" "--always-turbofan"; do printf "%-20s" "${m:-обычно}"; for k in 1 2 3 4 5; do printf "%s " "$(t node $m "$NPM" --version)"; done; echo; done
echo "## сколько функций доходит до верхних ярусов при этом старте"
echo "с байткодом: $(node --print-bytecode "$NPM" --version 2>/dev/null | grep -c '^\[generated bytecode for function')"
echo "Maglev, функций:   $(node --trace-opt "$NPM" --version 2>&1 | grep 'completed.*MAGLEV' | grep -o '<JSFunction [^ >]*' | sort -u | wc -l)"
echo "TurboFan, функций: $(node --trace-opt "$NPM" --version 2>&1 | grep 'completed optimizing.*TURBOFAN' | grep -o '<JSFunction [^ >]*' | sort -u | wc -l)"
echo "## --always-turbofan: запросов на оптимизацию против готового TurboFan-кода"
AT=$(node --always-turbofan --trace-opt "$NPM" --version 2>&1)
echo "because --always-turbofan: $(echo "$AT" | grep -c 'because --always-turbofan')"
echo "completed TurboFan:        $(echo "$AT" | grep -c 'completed optimizing.*TURBOFAN')"
