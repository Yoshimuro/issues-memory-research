#!/bin/bash
# usage: run.sh script.js "name1 name2 ..." [extra flags]  -> prints bytecode per function on node20/22/24 and d8 (15.6)
S=$1; NAMES=$2; shift 2
D8=/tmp/claude-0/-home-user-issues-memory-research/dacf359b-9898-588d-b8f1-20fd1e3f2945/scratchpad/d8/rel/d8
ENG=${ENGINES:-"node20:/opt/node20/bin/node node22:/opt/node22/bin/node node24:/opt/nvm/versions/node/v24.21.0/bin/node d8:$D8"}
for e in $ENG; do
  n=${e%%:*}; b=${e#*:}
  for f in $NAMES; do
  echo "=============== $n :: $f"
  $b --print-bytecode --print-bytecode-filter="$f" "$@" $S 2>&1 | grep -v '^\s*$' | grep -v -E '^(Parameter count|Register count|Frame size|OSR urgency|Bytecode age|Constant pool|Handler Table|Source Position|Bytecode length|\[generated bytecode)' | sed -E 's/^ *([0-9]+ )?(S> |E> )?0x[0-9a-f]+ @ +/  /; s/^ +[0-9]+ (S|E)> +0x[0-9a-f]+ @ +/  /'
  done
done
