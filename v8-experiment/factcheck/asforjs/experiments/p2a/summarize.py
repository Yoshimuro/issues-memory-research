import re,sys
cur=None; out={}; order=[]
for line in open(sys.argv[1]):
    m=re.match(r'\[generated bytecode for function: (\S+)',line)
    if m:
        cur=m.group(1)
        if cur in out: cur=None; continue
        out[cur]={'hdr':[], 'ins':[]}; order.append(cur); continue
    if cur is None: continue
    if re.match(r'(Bytecode length|Parameter count|Register count|Frame size)',line):
        out[cur]['hdr'].append(line.strip()); continue
    m=re.search(r'@\s+\d+ : ([0-9a-f ]+?)\s{2,}(\S.*)$',line)
    if m: out[cur]['ins'].append(m.group(2).strip())
    if line.startswith('Constant pool'): cur=None
for f in order:
    print('%s | %s\n    %s'%(f,'; '.join(out[f]['hdr']),' ; '.join(out[f]['ins'])))
